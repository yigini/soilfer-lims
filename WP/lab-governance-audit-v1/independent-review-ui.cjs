'use strict';
const fs=require('fs'),path=require('path'),{createRequire}=require('module');
const root=path.resolve(__dirname,'../..'),req=createRequire(path.join(root,'server/package.json'));
const outputDir=path.join(__dirname,'independent-review');
const report=JSON.parse(fs.readFileSync(path.join(outputDir,'probe-results.json'),'utf8'));
const dbPath=path.resolve(report.database);
if(!dbPath.startsWith(outputDir+path.sep)||!path.basename(dbPath).startsWith('disposable-')) throw Error('Unsafe database');
process.env.NODE_ENV='test';process.env.DATABASE_PATH=dbPath;process.env.DATABASE_URL=`file:${dbPath}`;process.env.JWT_SECRET='independent-review-only-not-production';
const prisma=req('./prisma'),app=req('./app'),express=req('express'),jwt=req('jsonwebtoken');
const {chromium}=require('C:/Users/yigin/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
app.use(express.static(path.join(root,'client/dist')));
app.use((r,s,n)=>r.path.startsWith('/api')?n():s.sendFile(path.join(root,'client/dist/index.html')));
async function main(){
 const user=await prisma.user.findUnique({where:{id:'review-manager'}});
 const token=jwt.sign({id:user.id,username:user.username,role:user.role,tokenVersion:user.tokenVersion},process.env.JWT_SECRET,{expiresIn:'1h'});
 const server=app.listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));
 const origin=`http://127.0.0.1:${server.address().port}`;
 const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];
 await page.route('**/*',route=>new URL(route.request().url()).hostname==='127.0.0.1'?route.continue():route.abort());
 await page.addInitScript(({token,user})=>{localStorage.setItem('token',token);localStorage.setItem('user',JSON.stringify(user));},{token,user:{id:user.id,username:user.username,name:'Fictional Lab Manager',role:user.role,labId:user.labId,language:'en'}});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(origin+'/admin/labs?labId=REVIEW-A&tab=people');
 await Promise.race([page.locator('table').waitFor({timeout:15000}), page.getByText('No staff accounts matching the selected criteria.').waitFor({timeout:15000})]).catch(()=>{});
 await page.screenshot({path:path.join(outputDir,'actual-ui-empty-people.png'),fullPage:true});
 const staffCount=await prisma.user.count({where:{labId:'REVIEW-A'}});
 const peopleText=await page.locator('body').innerText();
 await page.getByRole('button',{name:'Invite a Person',exact:true}).click();
 await page.getByText('Full Name', {exact:false}).first().waitFor({timeout:5000}).catch(()=>{});
 const modalText=await page.locator('body').innerText();
 const selects=await page.locator('select').evaluateAll(es=>es.map(e=>({value:e.value,options:[...e.options].map(o=>({value:o.value,text:o.text}))})));
 await page.screenshot({path:path.join(outputDir,'actual-ui-invite.png'),fullPage:true});
 const inputs=await page.locator('input').evaluateAll(es=>es.map(e=>({type:e.type,placeholder:e.placeholder})));
 const emptyPeopleShown = peopleText.includes('No staff accounts');
 fs.writeFileSync(path.join(outputDir,'ui-results.json'),JSON.stringify({timestamp:new Date().toISOString(),origin,staffCount,emptyPeopleShown,selects,inputs,modalText,errors},null,2));
 await browser.close();await new Promise(r=>server.close(r));await prisma.$disconnect();console.log(JSON.stringify({staffCount,emptyPeopleShown,selects,errors}));
}
main().then(()=>process.exit(0)).catch(e=>{console.error(e);process.exit(1)});
